  function parse(src) {
    var lx = new Lexer(src), pool = new Pool();
    var ss = [0], vs = [null];
    var state = 0, yychar = -2 /* YYEMPTY */, yylval = null, token = 0;
    var lacEstablished = false;
    var res = { ok: false, ast: null, aborted: false, error: null, oom: false, lexer: lx, pool: pool };

    function lac(tok) {         /* yy_lac: can tok eventually be shifted? 0 yes, 1 no */
      if (tok === 2) return 1;
      var es = ss.slice();
      for (;;) {
        var st = es[es.length - 1];
        var rule = T.pact[st], n;
        if (rule === T.YYPACT_NINF || (rule += tok) < 0 || T.YYLAST < rule || T.check[rule] !== tok) {
          rule = T.defact[st];
          if (rule === 0) return 1;
        } else {
          rule = T.table[rule];
          if (0 < rule) return 0;
          rule = -rule;
        }
        n = T.r2[rule];
        es.length -= n;
        var lhs = T.r1[rule] - T.YYNTOKENS, top = es[es.length - 1];
        var yi = T.pgoto[lhs] + top;
        es.push(0 <= yi && yi <= T.YYLAST && T.check[yi] === top ? T.table[yi] : T.defgoto[lhs]);
      }
    }
    function establish() {      /* YY_LAC_ESTABLISH: true means report an error */
      if (!lacEstablished) { lacEstablished = true; return lac(token) === 1; }
      return false;
    }
    function action(rule, len) {
      var v = function (i) { return vs[vs.length - len + i - 1]; };
      var val = len ? v(1) : null;
      switch (rule) {
        case 2: res.ast = v(1); break;
        case 3: val = pool.append(v(1), pool.list(v(2), lx.lineno - 1)); break;
        case 4: val = pool.list(v(1), lx.lineno - 1); break;
        case 5: case 6: case 7: val = v(1); break;
        case 8: val = pool.loop("@", v(2), v(3)); break;
        case 9: val = pool.cond(v(2), v(3), null); break;
        case 10: val = pool.cond(v(2), v(3), v(4)); break;
        case 11: val = pool.op(":", pool.vr(v(1)), v(2)); break;
        case 12: val = pool.op("p", null, v(2)); break;
        case 13: val = pool.op("o", v(2), v(3)); break;
        case 14: val = pool.op("A", pool.vr(v(1)), v(3)); break;
        case 15: val = pool.op("B", pool.vr(v(1)), v(3)); break;
        case 16: val = pool.op("C", pool.vr(v(1)), v(3)); break;
        case 17: val = pool.op("D", pool.vr(v(1)), v(3)); break;
        case 18: val = pool.op("E", pool.vr(v(1)), v(3)); break;
        case 19: val = pool.op("F", pool.vr(v(1)), v(3)); break;
        case 20: val = pool.lit(v(1)); break;
        case 21: val = pool.vr(v(1)); break;
        case 22: val = pool.op("+", v(1), v(3)); break;
        case 23: val = pool.op("-", v(1), v(3)); break;
        case 24: val = pool.op("*", v(1), v(3)); break;
        case 25: val = pool.op("/", v(1), v(3)); break;
        case 26: val = pool.op("-", null, v(2)); break;
        case 27: val = pool.op("^", v(1), v(3)); break;
        case 28: val = pool.op("%", v(1), v(3)); break;
        case 29: val = pool.op("=", v(1), v(3)); break;
        case 30: val = pool.op(">", v(1), v(3)); break;
        case 31: val = pool.op("<", v(1), v(3)); break;
        case 32: val = pool.op("l", v(1), v(3)); break;
        case 33: val = pool.op("g", v(1), v(3)); break;
        case 34: val = pool.op("~", v(1), v(3)); break;
        case 35: val = pool.op("!", null, v(2)); break;
        case 36: val = v(2); break;
        case 37: case 38: return { abort: true };
      }
      return { val: val };
    }

    try {
      for (;;) {
        /* yynewstate */
        if (state === T.YYFINAL) { res.ok = true; return res; }   /* YYACCEPT */
        var n = T.pact[state], rule = -1, isErr = false;
        if (n === T.YYPACT_NINF) {
          rule = T.defact[state]; if (rule === 0) isErr = true;
        } else {
          if (yychar === -2) { var t = lx.lex(); yychar = t.code; yylval = t.val; }
          token = yychar <= 0 ? 0 : translate(yychar);
          if (yychar <= 0) yychar = 0;
          n += token;
          if (n < 0 || T.YYLAST < n || T.check[n] !== token) {
            if (establish()) isErr = true;
            else { rule = T.defact[state]; if (rule === 0) isErr = true; }
          } else {
            n = T.table[n];
            if (n <= 0) {
              rule = -n;
              if (establish()) isErr = true;
            } else {
              /* shift */
              state = n; ss.push(state); vs.push(yylval); yychar = -2; lacEstablished = false;
              continue;
            }
          }
        }
        if (isErr) {
          res.error = "syntax";
          return res;          /* no error rules: recovery pops the stack and aborts */
        }
        var len = T.r2[rule];
        var r = action(rule, len);
        if (r.abort) { res.aborted = true; return res; }
        ss.length -= len; vs.length -= len;
        vs.push(r.val);
        var lhs = T.r1[rule] - T.YYNTOKENS, top = ss[ss.length - 1];
        var yi = T.pgoto[lhs] + top;
        state = (0 <= yi && yi <= T.YYLAST && T.check[yi] === top) ? T.table[yi] : T.defgoto[lhs];
        ss.push(state);
      }
    } catch (e) {
      if (e && e.oom) { res.oom = true; return res; }
      throw e;
    }
  }

  /* ------------------------------------------------------- C number output */
  /* printf("%g") as glibc prints it: six significant digits, exact decimal
     expansion of the double, ties to even. */
  function exactDecimal(v) {      /* v finite, > 0: returns {digits, exp} with v = 0.digits x 10^exp */
    var buf = new DataView(new ArrayBuffer(8));
    buf.setFloat64(0, v);
    var hi = buf.getUint32(0), lo = buf.getUint32(4);
    var e = (hi >>> 20) & 0x7ff;
    var m = (BigInt(hi & 0xfffff) << 32n) | BigInt(lo);
    if (e === 0) e = 1; else m |= 1n << 52n;
    e -= 1075;                    /* v = m * 2^e */
    var num, scale = 0;
    if (e >= 0) { num = m << BigInt(e); }
    else { num = m * (5n ** BigInt(-e)); scale = -e; }  /* v = num / 10^scale */
    var d = num.toString();
    return { digits: d, exp: d.length - scale };
  }
  function roundDigits(digits, p) {  /* round digit string to p digits, half to even */
    if (digits.length <= p) return { d: digits + "0".repeat(p - digits.length), carry: 0 };
    var head = digits.slice(0, p), rest = digits.slice(p);
    var first = rest.charCodeAt(0) - 48, tail = /[1-9]/.test(rest.slice(1));
    var up = first > 5 || (first === 5 && (tail || ((head.charCodeAt(p - 1) - 48) & 1)));
    if (!up) return { d: head, carry: 0 };
    var b = (BigInt(head) + 1n).toString();
    if (b.length > p) return { d: b.slice(0, p), carry: 1 };
    return { d: b, carry: 0 };
  }
  /* NaN sign. On x86-64 a freshly generated NaN has its sign bit set (glibc prints
     "-nan"); an operation on a NaN operand passes the first NaN operand through, and
     glibc's pow() clears the sign for an odd whole-number exponent. JavaScript cannot
     see a NaN's sign, so NaN values are carried as these two objects. */
  var NNAN = { nan: -1 }, PNAN = { nan: 1 };
  function isN(v) { return typeof v === "object" && v !== null; }
  function fresh(r) { return r !== r ? NNAN : r; }
  function fmtG(v) {
    if (isN(v)) return v.nan < 0 ? "-nan" : "nan";
    if (v !== v) return "-nan";
    if (v === Infinity) return "inf";
    if (v === -Infinity) return "-inf";
    var neg = v < 0 || (v === 0 && 1 / v < 0);
    var a = Math.abs(v), P = 6, s;
    if (a === 0) return neg ? "-0" : "0";
    var ex = exactDecimal(a);
    var r = roundDigits(ex.digits.replace(/^0+/, ""), P);
    var X = ex.exp - 1 + r.carry;  /* decimal exponent of the leading digit */
    var d = r.d;
    if (X < P && X >= -4) {
      if (X >= 0) s = d.slice(0, X + 1) + (X + 1 < P ? "." + d.slice(X + 1) : "");
      else s = "0." + "0".repeat(-X - 1) + d;
      if (s.indexOf(".") >= 0) s = s.replace(/0+$/, "").replace(/\.$/, "");
    } else {
      var mant = d[0] + "." + d.slice(1);
      mant = mant.replace(/0+$/, "").replace(/\.$/, "");
      s = mant + "e" + (X < 0 ? "-" : "+") + (Math.abs(X) < 10 ? "0" : "") + Math.abs(X);
    }
    return (neg ? "-" : "") + s;
  }
  function toCInt(v) {            /* (int)v on x86-64: out of range or NaN gives INT_MIN */
    if (isN(v) || v !== v || v >= 2147483648 || v <= -2147483649) return -2147483648;
    return Math.trunc(v);
  }
  function isOddInt(y) { return !isN(y) && Number.isInteger(y) && Math.abs(y) < 9007199254740992 && Math.abs(y % 2) === 1; }
  function cPow(x, y) {           /* glibc pow(), including its special cases */
    if (x === 1) return 1;
    if (y === 0) return 1;
    if (isN(x)) return isOddInt(y) ? PNAN : x;
    if (isN(y)) return y;
    if (x === -1 && (y === Infinity || y === -Infinity)) return 1;
    return fresh(Math.pow(x, y));
  }
  function arith(op, x, y) {      /* + - * / and fmod (JavaScript % is C fmod) */
    if (isN(x)) return x;
    if (isN(y)) return y;
    switch (op) {
      case "+": return fresh(x + y); case "-": return fresh(x - y); case "*": return fresh(x * y);
      case "/": return fresh(x / y); case "%": return fresh(x % y);
    }
    return fresh(x + y);
  }
  function truthy(v) { return isN(v) || v !== 0; }   /* C: a double is true unless it is 0 (NaN is true) */

  /* --------------------------------------------------------------- eval.c */
  var GLOBALS_INIT = [0, 1, 2, -1, 3.141592653589793, 10, 0, 0];
  var VAR_NAMES = ["a", "b", "c", "x", "y", "z", "sum", "count"];

  function StepLimit() {}
  function evaluate(ast, opts) {
    opts = opts || {};
    var limit = opts.maxSteps || 200000;
    var g = GLOBALS_INIT.slice();
    var out = [], events = [], steps = 0;
    function line(s, ev) { out.push(s); if (ev) events.push(ev); }
    function bin(op, x, y) {
      if (op === "^") return cPow(x, y);
      if ("+-*/%".indexOf(op) >= 0) return arith(op, x, y);
      if (op === "!") return y === 0 ? 1 : 0;
      if (isN(x) || isN(y)) return op === "~" ? 1 : 0;
      switch (op) {
        case "=": return x === y ? 1 : 0; case "<": return x < y ? 1 : 0;
        case ">": return x > y ? 1 : 0; case "l": return x <= y ? 1 : 0;
        case "g": return x >= y ? 1 : 0; case "~": return x !== y ? 1 : 0;
      }
      throw new Error("unrecognized operator " + op);
    }
    function ev(n) {
      if (!n) return 0;
      if (++steps > limit) throw new StepLimit();
      switch (n.t) {
        case "Num": return n.num;
        case "Var": return g[n.op];
        case "Exp":
          var op = n.op, k, y;
          if (op === ":" || "ABCDEF".indexOf(op) >= 0) {
            k = n.lop.op; y = ev(n.rop);
            switch (op) {
              case ":": g[k] = y; break;
              case "A": g[k] = arith("+", g[k], y); break;
              case "B": g[k] = arith("-", g[k], y); break;
              case "C": g[k] = arith("*", g[k], y); break;
              case "D": g[k] = arith("/", g[k], y); break;
              case "E": g[k] = cPow(g[k], y); break;
              case "F": g[k] = arith("%", g[k], y); break;
            }
            events.push({ type: "set", v: k, val: g[k] });
            return g[k];
          }
          if (op === "p") {
            y = ev(n.rop);
            var txt = (!isN(y) && isFinite(y)) ? fmtG(y) : "<" + fmtG(y) + ">";
            line(txt, { type: "print", val: y, text: txt });
            return y;
          }
          if (op === "o") {
            var ch = ev(n.lop); y = ev(n.rop);
            var t2 = "#OUT(" + toCInt(ch) + ", " + fmtG(y) + ")";
            line(t2, { type: "out", channel: toCInt(ch), val: y, arg: fmtG(y), text: t2 });
            return y;
          }
          return bin(op, ev(n.lop), ev(n.rop));
        case "List":
          var r = 0;
          for (var nd = n; nd; nd = nd.rop) {
            if (nd.linenum >= 1) line("#LINECHANGE(" + nd.linenum + ")", { type: "line", line: nd.linenum });
            r = ev(nd.e);
          }
          return r;
        case "Cond":
          return truthy(ev(n.e)) ? ev(n.lop) : (n.rop ? ev(n.rop) : 0);
        case "Loop":
          var rv = 0;
          while (truthy(ev(n.lop))) rv = ev(n.rop);
          return rv;
      }
      return 0;
    }
    var stopped = false;
    try { ev(ast); } catch (e) { if (e instanceof StepLimit) stopped = true; else throw e; }
    return { stdout: out, events: events, vars: g, steps: steps, stopped: stopped };
  }

  /* run(src): what `abc file` prints. stdout and stderr as arrays of lines. */
  function run(src, opts) {
    var p = parse(src);
    var res = { stdout: [], stderr: [], events: [], vars: GLOBALS_INIT.slice(), tokens: p.lexer.trace,
                status: "ok", stopped: false, nodes: p.pool.used };
    if (p.oom) { res.stderr.push("ERROR: ran out of memory :("); res.status = "oom"; return res; }
    if (p.error) {
      var e = p.lexer.err;
      if (e.unrecognized) {
        res.stderr.push("ERROR: Unexpected Token(s): " + e.text);
        res.stderr.push("       on line " + e.line + ", column " + e.col);
        res.stdout.push("#SYNTAXERROR(" + e.line + ", " + e.col + ")");
        res.errorAt = { line: e.line, col: e.col, text: e.text };
      } else {
        res.stderr.push("ERROR: syntax error");
        var last = p.lexer.trace[p.lexer.trace.length - 1];
        res.errorAt = last ? { line: last.line, col: last.col, text: last.text } : null;
      }
      res.status = "syntax";
      return res;
    }
    if (p.aborted) { res.status = "aborted"; return res; }   /* EXPRESSION: ERROR -> YYABORT, silently */
    var r = evaluate(p.ast, opts);
    res.stdout = r.stdout; res.events = r.events; res.vars = r.vars; res.stopped = r.stopped; res.steps = r.steps;
    if (r.stopped) res.status = "stopped";
    return res;
  }

