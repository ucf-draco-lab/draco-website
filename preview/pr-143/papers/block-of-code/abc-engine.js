  Lexer.prototype.lex = function () {
    var s = this.src;
    for (;;) {
      if (this.pos >= s.length) return { code: -1, text: "" };   /* <<EOF>> */
      var best = -1, bestLen = 0;
      for (var i = 0; i < RULES.length; i++) {
        var re = RULES[i].re;
        re.lastIndex = this.pos;
        var m = re.exec(s);
        if (m && m[0].length > bestLen) { best = i; bestLen = m[0].length; }
      }
      if (best < 0) {          /* only a lone "\n"-free nothing: cannot happen */
        this.pos++; continue;
      }
      var r = RULES[best], text = s.substr(this.pos, bestLen);
      var startCol = this.colnum, startLine = this.lineno;
      this.pos += bestLen;
      var nl = (text.match(/\n/g) || []).length;
      this.lineno += nl;
      var out = null;
      if (r.act === "comment") { this.colnum = 1; continue; }
      if (r.act === "space") { this.colnum++; continue; }
      if (r.act === "newline") { this.colnum = 1; continue; }
      if (r.act === "run") { out = { code: -1, text: text }; }
      else if (r.act === "numlen") {
        this.colnum += bestLen;
        out = { code: TK.NUM, val: parseFloat(text), text: text };
      } else if (r.act === "quit" || r.act === "error") {
        /* File mode: quit/exit/q are not commands, so both rules flag an error. */
        this.err.line = this.lineno; this.err.col = this.colnum;
        this.err.text = text; this.err.unrecognized = true;
        out = { code: TK.ERROR, text: text };
      } else if (r.v !== undefined) {
        this.colnum += r.col;
        out = { code: TK.VAR, val: r.v, text: text };
      } else {
        this.colnum += r.col;
        out = { code: r.tok, text: text };
      }
      out.line = startLine; out.col = startCol;
      this.trace.push(out);
      return out;
    }
  };

