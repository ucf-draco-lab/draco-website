"""Record sector-level READ/WRITE requests issued by the pyfatfs FAT driver.

Usage: pip install pyfatfs==1.1.0 && python3 gen_traces.py 32768
Writes traces_raw.json and ../fat-traces.json (the page's data) in the current folder's parent.
Every read() or write() the driver makes on the image becomes one command covering the
512-byte blocks it touches, in the order issued.
"""
import builtins, io, json, os, sys, random
import pyfatfs.PyFat as PF
import fs
from pyfatfs.PyFatFS import PyFatFS

SECTOR = 512
LOG = []
class LogFile(io.RawIOBase):
    def __init__(self, f): self.f = f
    def seek(self, o, w=0): return self.f.seek(o, w)
    def tell(self): return self.f.tell()
    def seekable(self): return True
    def readable(self): return True
    def writable(self): return True
    def _log(self, op, pos, n):
        if n <= 0: return
        a = pos // SECTOR; b = (pos + n - 1) // SECTOR
        LOG.append((op, a, b - a + 1))
    def read(self, n=-1):
        p = self.f.tell(); d = self.f.read(n); self._log("READ", p, len(d)); return d
    def write(self, d):
        p = self.f.tell(); r = self.f.write(d); self._log("WRITE", p, len(d)); return r
    def flush(self): self.f.flush()
    def truncate(self, n=None): return self.f.truncate(n)
    def close(self): self.f.close()
    def fileno(self): return self.f.fileno()
_open = builtins.open
def lopen(name, mode="r", *a, **k):
    f = _open(name, mode, *a, **k)
    if str(name).endswith(".img"): return LogFile(f)
    return f
PF.open = lopen

IMG = "dev.img"; NSEC = int(sys.argv[1]) if len(sys.argv) > 1 else 8192
def fresh():
    with _open(IMG, "wb") as f: f.truncate(NSEC * SECTOR)
def take():
    t = list(LOG); LOG.clear(); return t

out = {}
fresh(); LOG.clear()
pf = PF.PyFat(); pf.mkfs(IMG, fat_type=PF.PyFat.FAT_TYPE_FAT16 if NSEC >= 8400*2 else PF.PyFat.FAT_TYPE_FAT12, label="USBKEY")
pf.close()
out["format"] = take()

rng = random.Random(2008)
files = {"F%02d.TXT" % i: bytes(rng.randrange(256) for _ in range(rng.choice([700, 3000, 9000, 20000, 48000]))) for i in range(12)}
def openfs(): return PyFatFS(IMG)
take()
v = openfs()
for n, d in files.items():
    with v.openbin("/" + n, "w") as f:
        for i in range(0, len(d), 4096): f.write(d[i:i+4096])
v.close()
out["write_files"] = take()
v = openfs()
for n in list(files)[:6]:
    with v.openbin("/" + n, "r") as f:
        while f.read(4096): pass
v.close()
out["read_files"] = take()
v = openfs()
for n in list(files)[::2]:
    v.remove("/" + n)
v.close()
out["delete_files"] = take()
json.dump({"sectors": NSEC, "traces": out}, open("traces_raw.json", "w"))
for k, t in out.items():
    print(k, len(t), "ops; max lba", max(a + l - 1 for _, a, l in t), "first", t[:6])

labels = {"format": "Format", "write_files": "Write 12 files", "read_files": "Read 6 files", "delete_files": "Delete 6 files"}
page = {"source": "pyfatfs 1.1.0 FAT driver on a 16 MiB FAT16 image (32,768 blocks of 512 bytes; 4 blocks per cluster; FATs at blocks 1-32 and 33-64; root directory 65-96; data from 97). Generated by papers/usb-self-protecting/reference/gen_traces.py.",
        "blocks": NSEC, "layout": {"boot": [0, 0], "fat1": [1, 32], "fat2": [33, 64], "root": [65, 96], "data": 97},
        "traces": {k: {"label": labels[k], "ops": [[0 if o == "READ" else 1, a, l] for o, a, l in t]} for k, t in out.items()}}
json.dump(page, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fat-traces.json"), "w"), separators=(",", ":"))
